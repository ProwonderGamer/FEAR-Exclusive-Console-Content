// Command genhashes computes size / SHA-256 / first-16-bytes for the files the
// installer verifies and writes internal/refdata/hashes_gen.go.
//
//	go run ./cmd/genhashes -ps3 <.../USRDIR/game> -x360 <disc root> -out internal/refdata/hashes_gen.go
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"
)

// Files verified on a decrypted PS3 disc, relative to PS3_GAME/USRDIR/game.
var ps3Files = []string{
	"worlds/release/sfod_d.wld", "worlds/release/sfod_d.wldclnt", "worlds/release/sfod_d.wldsrvr",
	"worlds/release/sfod_d.matcat", "worlds/release/sfod_d.texcat",
	"database/loki.gamedb", "database_anim/anim.gamedb", "profiledatabase/defaults.gamedb",
	"minicatalog.cat", "lipsenglish.cat", "snd/english.cat", "snd/sfx.cat",
}

// Files verified on an Xbox 360 disc, relative to the disc root.
var x360Files = []string{
	"default.xex",
	"Game/database/Loki.gamedb", "Game/database_anim/Anim.gamedb", "Game/database_anim/Anim.anmtree",
	"Game/ProfileDatabase/Defaults.gamedb", "Game/lipsEnglish.cat",
	"Game/Worlds/Release/Holiday.wld", "Game/Worlds/Release/Holiday.wldclnt", "Game/Worlds/Release/Holiday.wldsrvr",
	"Game/Worlds/Release/Holiday.matCat", "Game/Worlds/Release/Holiday.texCat",
	"Game/Snd/SFX.xwb", "Game/Snd/VoiceEnglish.xwb",
}

func main() {
	ps3 := flag.String("ps3", "", "PS3 game root (PS3_GAME/USRDIR/game)")
	x360 := flag.String("x360", "", "Xbox 360 disc root")
	out := flag.String("out", "internal/refdata/hashes_gen.go", "output file")
	flag.Parse()
	var b strings.Builder
	b.WriteString("// Code generated by cmd/genhashes; DO NOT EDIT.\n\npackage refdata\n\n")
	emit := func(name, root string, files []string) {
		fmt.Fprintf(&b, "// %s lists the verified files.\nvar %s = []Item{\n", name, name)
		for _, rel := range files {
			it := hashFile(filepath.Join(root, filepath.FromSlash(rel)))
			fmt.Fprintf(&b, "\t{Path: %q, Size: %d, SHA256: %q, Magic: %q},\n", rel, it.size, it.sum, it.magic)
			log.Printf("%-45s %12d %s", rel, it.size, it.sum[:16])
		}
		b.WriteString("}\n\n")
	}
	emit("PS3Files", *ps3, ps3Files)
	emit("X360Files", *x360, x360Files)
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

type info struct {
	size       int64
	sum, magic string
}

func hashFile(p string) info {
	f, err := os.Open(p)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	h := sha256.New()
	n, err := io.Copy(h, f)
	if err != nil {
		log.Fatal(err)
	}
	m := make([]byte, 16)
	f.ReadAt(m, 0)
	return info{n, hex.EncodeToString(h.Sum(nil)), hex.EncodeToString(m)}
}
